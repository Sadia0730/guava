"""Compact main results table: every dataset and all clips, PSNR / SSIM / LPIPS, ten rows grouped by what each method may
use (one photo vs. training on the person). Reads phase3_dnt/results_ext_a6.csv (written by ext_tables.py --amend6; the
registered scores, nothing recomputed). Writes table_main_compact.{tex,md,pdf,png}. CPU only.

Rows: supplied body parameters only. Estimated-pose rows, update budgets and fine-tuning + update stay in their own tables.
Marks: bold = best, underline = second best within each group, per column (compared on the displayed values)."""
import argparse, csv
from pathlib import Path

P3 = Path(__file__).resolve().parents[1]
O = Path("/vault/research/COS/VIRLab/ubx858/persistent_avatar/outputs/guava_fb/reports/paper_tables")
DS = [("ubody", "UBody", 30), ("peoplesnapshot", "People-Snapshot", 24), ("neuman", "NeuMan", 6), ("xhumans", "X-Humans", 3),
      ("ubc", "UBC-Fashion", 100), ("all_clips", "All clips", 163)]
MET = [("psnr", "PSNR", "$\\uparrow$", "↑"), ("ssim", "SSIM", "$\\uparrow$", "↑"), ("lpips", "LPIPS", "$\\downarrow$", "↓")]
GROUPS = [("Initialized from one photo, no training on the test person",
           [("guava", "GUAVA~\\cite{guava}", "GUAVA", "photo"), ("lhm_facefix", "LHM~\\cite{lhm}", "LHM", "photo"),
            ("lhmpp", "LHM++~\\cite{lhmpp}", "LHM++", "photo"), ("idol", "IDOL~\\cite{idol}", "IDOL", "photo"),
            ("fb_gt", "RAGA", "RAGA", "photo"), ("fb_update100", "RAGA with update", "RAGA with update", "photo + appearance update")]),
          ("Training on the test person",
           [("gart", "GART~\\cite{gart}", "GART", "video"), ("gaussianavatar", "GaussianAvatar~\\cite{gaussianavatar}", "GaussianAvatar", "video"),
            ("exavatar_gtface", "ExAvatar~\\cite{exavatar}", "ExAvatar", "video"), ("ft_gt", "RAGA, fine-tuned", "RAGA, fine-tuned", "video")])]


def load(csv_path):
    v = {}
    with open(csv_path) as fh:
        for r in csv.DictReader(fh): v[(r["method"], r["column"], r["metric"])] = float(r["mean"])
    return v


def fmt(m, x):
    return f"{x:.2f}" if m == "psnr" else f"{x:.3f}"


def marks(V):
    """{(method, dataset, metric): 1 | 2}: best / second best displayed value within each group."""
    out = {}
    for _, rows in GROUPS:
        for d, _, _ in DS:
            for m, *_ in MET:
                vals = sorted({float(fmt(m, V[(k, d, m)])) for k, *_ in rows}, reverse=m != "lpips")
                for k, *_ in rows:
                    x = float(fmt(m, V[(k, d, m)]))
                    if x in vals[:2]: out[(k, d, m)] = vals.index(x) + 1
    return out


CAPTION = ("Avatar quality per dataset (number of clips in parentheses) and over all 163 clips. Every method receives the supplied "
           "body parameters of the source and of each test frame. Top: avatars initialized from one photo, with no training on the "
           "test person; RAGA with update additionally accumulates the reconstruction frames that follow the photo, with fixed "
           "network weights (offline). Bottom: methods trained on the person's reconstruction frames. Bold: best; underline: second "
           "best, within each group. Scores average the test frames of a clip, then clips. Estimated poses and update budgets: "
           "Table~\\ref{tab:ablation_update}.")


MARKS = "boldunder"                                                      # set by --marks


CAPTION_RAGA = ("\\textbf{Reconstruction quality per dataset and on all 163 clips.} Clip counts are in parentheses. All rows use "
                "supplied driving parameters. The first block initializes from one photo without training on the test person. The "
                "live appearance update also uses later images of that person with fixed network weights; its quality is measured by "
                "offline fusion of reconstruction frames. Video methods train on the reconstruction partition. Metrics average frames "
                "within each clip and then average clips equally. ExAvatar also receives supplied facial parameters. "
                "\\ragaFirst{Best} and \\ragaSecond{second best} values are marked within each block; ties share a rank.")


def tex(V, M):
    nd = len(DS)
    L = ["% Generated by phase3_dnt/eval_split/main_table_compact.py from phase3_dnt/results_ext_a6.csv; needs booktabs, graphicx,",
         "% colortbl (gray band on All clips; preamble.tex loads it)" + ("; \\ragaFirst / \\ragaSecond from sections/5_result.tex" if MARKS == "raga" else ""),
         "\\begin{table*}[t]", "\\centering", "\\caption{" + (CAPTION_RAGA if MARKS == "raga" else CAPTION) + "}", "\\label{tab:main}",
         "\\setlength{\\tabcolsep}{3pt}", "\\resizebox{\\textwidth}{!}{%",
         "\\begin{tabular}{ll" + "".join("@{\\hspace{8pt}}ccc" for _ in DS) + "}", "\\toprule"]
    gray = "\\cellcolor{black!6}"
    h1 = ["", ""] + [(f"\\multicolumn{{3}}{{c}}{{{gray}{n} ({c})}}" if d == "all_clips" else f"\\multicolumn{{3}}{{c}}{{{n} ({c})}}")
                     for d, n, c in DS]
    L += [" & ".join(h1) + " \\\\", "".join(f"\\cmidrule(lr){{{3 + 3 * i}-{5 + 3 * i}}}" for i in range(nd))]
    h2 = ["Method", "Appearance input"] + [(gray if d == "all_clips" else "") + f"{{\\scriptsize {lab}{arr}}}" for d, *_ in DS for _, lab, arr, _ in MET]
    L += [" & ".join(h2) + " \\\\", "\\midrule"]
    for gi, (gname, rows) in enumerate(GROUPS):
        if gi: L.append("\\midrule")
        L.append(f"\\multicolumn{{{2 + 3 * nd}}}{{l}}{{\\textit{{{gname}}}}} \\\\")
        for k, tname, _, inp in rows:
            cells = [tname, inp]
            for d, *_ in DS:
                for m, *_ in MET:
                    s = fmt(m, V[(k, d, m)]); r = M.get((k, d, m))
                    if MARKS == "raga": s = f"\\ragaFirst{{{s}}}" if r == 1 else (f"\\ragaSecond{{{s}}}" if r == 2 else s)
                    else: s = f"\\textbf{{{s}}}" if r == 1 else (f"\\underline{{{s}}}" if r == 2 else s)
                    cells.append((gray if d == "all_clips" else "") + s)
            L.append(" & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}}", "\\end{table*}"]
    return "\n".join(L) + "\n"


CELL_RGB = {1: (248, 205, 205), 2: (205, 220, 245)}                       # light tints of the paper's ragaBest red / ragaSecond blue


def tex_grid(V, M):
    """--marks cell: rank shown by cell background (best also bold), a border around every dataset group and every row."""
    nd = len(DS); ncol = 2 + 3 * nd
    cap = CAPTION_RAGA.replace("\\ragaFirst{Best} and \\ragaSecond{second best} values are marked",
                               "\\colorbox{ragaCellBest}{\\textbf{Best}} and \\colorbox{ragaCellSecond}{second best} cells are shaded")
    assert cap != CAPTION_RAGA
    L = ["% Generated by phase3_dnt/eval_split/main_table_compact.py --marks cell from phase3_dnt/results_ext_a6.csv;",
         "% needs graphicx and colortbl (preamble.tex loads colortbl)",
         "\\begin{table*}[t]", "\\centering",
         "\\definecolor{ragaCellBest}{RGB}{%d,%d,%d}" % CELL_RGB[1], "\\definecolor{ragaCellSecond}{RGB}{%d,%d,%d}" % CELL_RGB[2],
         "\\caption{" + cap + "}", "\\label{tab:main}",
         "\\setlength{\\tabcolsep}{3.5pt}", "\\renewcommand{\\arraystretch}{1.15}", "\\resizebox{\\textwidth}{!}{%",
         "\\begin{tabular}{|l|l|" + "|".join("ccc" for _ in DS) + "|}", "\\hline"]
    h1 = ["\\multicolumn{1}{|l|}{}", "\\multicolumn{1}{l|}{}"] + [f"\\multicolumn{{3}}{{c|}}{{{n} ({c})}}" for d, n, c in DS[:-1]]
    h1.append(f"\\multicolumn{{3}}{{c|}}{{\\textbf{{{DS[-1][1]} ({DS[-1][2]})}}}}")
    L += [" & ".join(h1) + " \\\\", f"\\cline{{3-{ncol}}}"]
    L += [" & ".join(["Method", "Appearance input"] + [f"{{\\scriptsize {lab}{arr}}}" for _ in DS for _, lab, arr, _ in MET]) + " \\\\", "\\hline\\hline"]
    for gi, (gname, rows) in enumerate(GROUPS):
        if gi: L.append("\\hline")
        L += [f"\\multicolumn{{{ncol}}}{{|l|}}{{\\textit{{{gname}}}}} \\\\", "\\hline"]
        for k, tname, _, inp in rows:
            cells = [tname, inp]
            for d, *_ in DS:
                for m, *_ in MET:
                    v = fmt(m, V[(k, d, m)]); r = M.get((k, d, m))
                    cells.append(f"\\cellcolor{{ragaCellBest}}\\textbf{{{v}}}" if r == 1 else (f"\\cellcolor{{ragaCellSecond}}{v}" if r == 2 else v))
            L += [" & ".join(cells) + " \\\\", "\\hline"]
    L += ["\\end{tabular}}", "\\end{table*}"]
    return "\n".join(L) + "\n"


def md(V, M):
    L = ["| Method | Appearance input | " + " | ".join(f"{n} {lab} {a}" for _, n, _ in DS for _, lab, _, a in MET) + " |",
         "|" + "---|" * (2 + 3 * len(DS))]
    for gname, rows in GROUPS:
        L.append(f"| *{gname}* |" + " |" * (1 + 3 * len(DS)))
        for k, _, name, inp in rows:
            c = []
            for d, *_ in DS:
                for m, *_ in MET:
                    s = fmt(m, V[(k, d, m)]); r = M.get((k, d, m)); c.append(f"**{s}**" if r == 1 else (f"<u>{s}</u>" if r == 2 else s))
            L.append(f"| {name} | {inp} | " + " | ".join(c) + " |")
    return "\n".join(L) + "\n\n" + CAPTION.replace("~\\ref{tab:ablation_update}", " (update ablation)") + "\n"


def render(V, M, out, name):
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family": "STIXGeneral", "mathtext.fontset": "stix", "pdf.fonttype": 42, "ps.fonttype": 42})
    W = 6.88; wm, wi, wn, gap = 1.02, 1.12, 0.245, 0.07
    xs, x = [], wm + wi
    for i in range(len(DS)):
        x += gap if i else 0.0
        for j in range(3): xs.append(x + j * wn)
        x += 3 * wn
    sc = W / x; xs = [v * sc for v in xs]; wn *= sc; wm *= sc; wi *= sc
    nrow = sum(len(r) + 1 for _, r in GROUPS); rh = 0.15; top = 0.04; H = top + 2 * rh + nrow * rh + 0.08
    f = plt.figure(figsize=(W, H)); fs = 6.0
    Y = lambda y: 1 - y / H
    def hl(y, lw, x0=0, x1=W): f.add_artist(plt.Line2D([x0 / W, x1 / W], [Y(y)] * 2, transform=f.transFigure, color="k", lw=lw))
    def tx(x_, y_, s, ha="center", **k): k.setdefault("fontsize", fs); f.text(x_ / W, Y(y_), s, ha=ha, va="center", **k)
    ya, yb = top, top + 2 * rh + nrow * rh
    cell = MARKS == "cell"
    gx0 = xs[3 * (len(DS) - 1)] - 0.02
    if not cell: f.add_artist(plt.Rectangle((gx0 / W, Y(yb)), (W - gx0) / W, (yb - ya) / H, transform=f.transFigure,
                                                                    color=(0.94, 0.94, 0.94), lw=0, zorder=-1))
    hl(ya, 0.9)
    for i, (d, n, c) in enumerate(DS):
        a_, b_ = xs[3 * i], xs[3 * i + 2] + wn; tx((a_ + b_) / 2, ya + rh / 2, f"{n} ({c})"); hl(ya + rh, 0.4, a_ + 0.01, b_ - 0.01)
        for j, (_, lab, _, arr) in enumerate(MET): tx(xs[3 * i + j] + wn / 2, ya + 1.5 * rh, lab + arr, fontsize=5.0)
    tx(0.03, ya + 1.5 * rh, "Method", ha="left"); tx(wm + 0.02, ya + 1.5 * rh, "Appearance input", ha="left")
    y = ya + 2 * rh; hl(y, 0.5)
    for gi, (gname, rows) in enumerate(GROUPS):
        if gi: hl(y, 0.4)
        tx(0.03, y + rh / 2, gname, ha="left", style="italic"); y += rh
        for k, _, label, inp in rows:
            tx(0.03, y + rh / 2, label, ha="left"); tx(wm + 0.02, y + rh / 2, inp, ha="left")
            for i, (d, *_) in enumerate(DS):
                for j, (m, *_) in enumerate(MET):
                    r = M.get((k, d, m)); cx = xs[3 * i + j] + wn / 2
                    if cell:
                        if r: f.add_artist(plt.Rectangle(((xs[3 * i + j] - 0.012) / W, Y(y + rh)), (wn + 0.024) / W, rh / H, transform=f.transFigure,
                                                         color=tuple(c / 255 for c in CELL_RGB[r]), lw=0, zorder=-1))
                        tx(cx, y + rh / 2, fmt(m, V[(k, d, m)]), fontweight="bold" if r == 1 else "normal")
                    elif MARKS == "raga":
                        col = {1: (180 / 255, 35 / 255, 35 / 255), 2: (35 / 255, 80 / 255, 170 / 255)}.get(r, "k")
                        tx(cx, y + rh / 2, fmt(m, V[(k, d, m)]), fontweight="bold" if r == 1 else "normal", color=col)
                    else:
                        tx(cx, y + rh / 2, fmt(m, V[(k, d, m)]), fontweight="bold" if r == 1 else "normal")
                        if r == 2: hl(y + rh * 0.84, 0.35, cx - wn * 0.36, cx + wn * 0.36)
            y += rh
            if cell: hl(y, 0.3)
    hl(y, 0.9)
    if cell:                                                               # borders: method / input columns and every dataset group
        for xv in [0.0, wm, xs[0] - 0.035] + [xs[3 * i] - 0.035 for i in range(1, len(DS))] + [W]:
            f.add_artist(plt.Line2D([xv / W] * 2, [Y(ya), Y(y)], transform=f.transFigure, color="k", lw=0.4))
    f.savefig(out / f"{name}.pdf"); f.savefig(out / f"{name}.png", dpi=300); plt.close(f)


def main():
    p = argparse.ArgumentParser(description=__doc__); p.add_argument("--csv", type=Path, default=P3 / "results_ext_a6.csv")
    p.add_argument("--out", type=Path, default=O); p.add_argument("--name", default="table_main_compact")
    p.add_argument("--marks", default="boldunder", choices=["boldunder", "raga", "cell"],
                   help="raga: the paper's \\ragaFirst / \\ragaSecond colour macros (defined in sections/5_result.tex), labels as there")
    a = p.parse_args(); global MARKS; MARKS = a.marks
    if MARKS in ("raga", "cell"):                                          # the paper's row label for the update row
        GROUPS[0][1][5] = ("fb_update100", "RAGA with update", "RAGA with update", "photo + live appearance update")
        GROUPS[1][1][3] = ("ft_gt", "RAGA, fine tuned", "RAGA, fine tuned", "video")
    V = load(a.csv); M = marks(V); a.out.mkdir(parents=True, exist_ok=True)
    for ext, txt in (("tex", tex_grid(V, M) if MARKS == "cell" else tex(V, M)), ("md", md(V, M))):                     # never overwrite: identical content is skipped
        f = a.out / f"{a.name}.{ext}"
        if f.exists(): assert f.read_text() == txt, f"{f} exists with other content; pick another --name"
        else: f.write_text(txt)
    assert not any((a.out / f"{a.name}.{e}").exists() for e in ("pdf", "png")), "preview exists; pick another --name"
    render(V, M, a.out, a.name)
    print(md(V, M))


if __name__ == "__main__":
    main()
