"""Ablation table of the appearance update (PREREG "Extended benchmark, amendment 7"): existing scores only, no new run.
Rows: video share 0 / 25 / 50 / 100 % (GT pose); pose source (SPRINT); with per-subject fine-tuning. Cells: all 163 clips PSNR /
SSIM / LPIPS (results_ext_a6.csv), mean of the five dataset means (PSNR), and the paired PSNR / LPIPS difference to the group's
reference with its 95 % CI (RESULTS_EXT_A6.md, same bootstrap as the main table). Descriptive extra (teaser_candidates.json): mean
PSNR gain of the 100 % update on test frames turned >= 135 deg from the photo, and UV texture coverage photo -> after the update.
Usage: python ablation_update_table.py --out-dir O/reports/ablation_update [--tex paper/raga_cvpr/tables/table_ablation_update.tex]"""
from __future__ import annotations

import argparse
import csv
import json
import re
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent; P3 = HERE.parent
ap = argparse.ArgumentParser(); ap.add_argument("--out-dir", required=True); ap.add_argument("--tex", default="")
ap.add_argument("--cands", default="/vault/research/COS/VIRLab/ubx858/persistent_avatar/outputs/guava_fb/reports/paper_figures/teaser_candidates.json")
a = ap.parse_args(); OUT = Path(a.out_dir); OUT.mkdir(parents=True, exist_ok=True)
V = {(r["method"], r["column"], r["metric"]): float(r["mean"]) for r in csv.DictReader(open(P3 / "results_ext_a6.csv"))}
md = (P3 / "RESULTS_EXT_A6.md").read_text().splitlines()
NAME = {"fb_gt": "Ours [SMPL-X GT]", "fb_update25": "Ours + update, 25 % of video", "fb_update50": "Ours + update, 50 % of video",
        "fb_update100": "Ours + update, 100 % of video", "fb_sprint": "Ours [SPRINT pose]",
        "fb_sprint_update100": "Ours + update, 100 % of video, SPRINT pose", "ft_gt": "Ours fine-tuned per subject [SMPL-X GT]",
        "ft_update100": "Ours fine-tuned per subject + update [SMPL-X GT]",
        "ft_sprint_update100": "Ours fine-tuned per subject + update [SPRINT pose]"}


def paired(m, ref):
    """(PSNR mean, lo, hi), (LPIPS mean, lo, hi) of row m - ref, all clips, from the paired-difference table."""
    key = f"| {NAME[m]} − {NAME[ref]} |"
    for line in md:
        if line.startswith(key):
            cells = [c.strip() for c in line.strip("|").split("|")]
            out = []
            for c in (cells[1], cells[3]):
                x = re.match(r"([+-]?[\d.]+) \[([+-]?[\d.]+), ([+-]?[\d.]+)\]", c); out.append(tuple(float(v) for v in x.groups()))
            return out
    raise KeyError(key)


# group title, reference, rows (method, configuration, pose, video, training)
G = [("Amount of video fused (supplied pose)", "fb_gt",
      [("fb_gt", "Photo only", "GT", "--", "none"), ("fb_update25", "+ update", "GT", "25\\%", "none"),
       ("fb_update50", "+ update", "GT", "50\\%", "none"), ("fb_update100", "+ update", "GT", "100\\%", "none")]),
     ("Estimated pose (fully automatic)", "fb_sprint",
      [("fb_sprint", "Photo only", "Est.", "--", "none"), ("fb_sprint_update100", "+ update", "Est.", "100\\%", "none")]),
     ("After per-subject fine-tuning (500 steps)", "ft_gt",
      [("ft_gt", "Fine-tuned", "GT", "--", "4 min"), ("ft_update100", "Fine-tuned + update", "GT", "100\\%", "4 min")])]

C = json.loads(Path(a.cands).read_text())
back = np.array([c["gain_back_mean"] for c in C if c.get("gain_back_mean") is not None])
cov0 = np.array([c["coverage_photo"] for c in C if c.get("coverage_photo") is not None])
cov1 = np.array([c["coverage_after"] for c in C if c.get("coverage_after") is not None])
extra = {"clips_with_turned_away_frames": int(len(back)), "gain_back_mean_db": round(float(back.mean()), 2),
         "share_of_those_clips_with_positive_gain": round(float((back > 0).mean()), 3),
         "coverage_photo_mean": round(float(cov0.mean()), 3), "coverage_after_mean": round(float(cov1.mean()), 3)}

rows_md = ["| Group | Configuration | Pose | Video fused | Training | PSNR ↑ | SSIM ↑ | LPIPS ↓ | PSNR, mean of datasets ↑ | Δ PSNR vs. group reference [95 % CI] | Δ LPIPS vs. group reference [95 % CI] |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
T = [r"% Generated by phase3_dnt/eval_split/ablation_update_table.py from results_ext_a6.csv / RESULTS_EXT_A6.md -- do not edit numbers.",
     r"\begin{table}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{3pt}",
     r"\caption{\textbf{Ablation of the appearance update} on all 163 test clips. \emph{Video fused}: share of the person's "
     r"reconstruction frames fused into the avatar after the photo, without gradient steps. $\Delta$: paired difference per clip to "
     r"the first row of each group, mean with 95\% bootstrap CI over people.}",
     r"\label{tab:ablation_update}", r"\resizebox{\columnwidth}{!}{%", r"\begin{tabular}{@{}lccccc@{}}", r"\toprule",
     r"Configuration & Video & PSNR$\uparrow$ & SSIM$\uparrow$ & LPIPS$\downarrow$ & $\Delta$PSNR \\", r"\midrule"]
for gi, (title, ref, rows) in enumerate(G):
    if gi: T.append(r"\midrule")
    T.append(rf"\multicolumn{{6}}{{@{{}}l}}{{\textit{{{title}}}}} \\")
    for m, conf, pose, vid, tr in rows:
        p, s, l, mac = V[(m, "all_clips", "psnr")], V[(m, "all_clips", "ssim")], V[(m, "all_clips", "lpips")], V[(m, "mean_of_ds", "psnr")]
        if m == ref: dp_md = dl_md = "reference"; dp_tex = "--"
        else:
            (dp, plo, phi), (dl, llo, lhi) = paired(m, ref)
            dp_md, dl_md = f"{dp:+.2f} [{plo:+.2f}, {phi:+.2f}]", f"{dl:+.3f} [{llo:+.3f}, {lhi:+.3f}]"
            dp_tex = f"${dp:+.2f}$ {{\\scriptsize[{plo:+.2f}, {phi:+.2f}]}}"
        rows_md.append(f"| {title} | {conf} | {pose} | {vid.replace(chr(92), '')} | {tr} | {p:.2f} | {s:.3f} | {l:.4f} | {mac:.2f} | {dp_md} | {dl_md} |")
        T.append(f"{conf} & {vid} & {p:.2f} & {s:.3f} & {l:.4f} & {dp_tex} \\\\")
T += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
note = (f"Turned-away views (descriptive, {extra['clips_with_turned_away_frames']} clips with test frames turned >= 135 deg from the photo): "
        f"the 100 % update changes PSNR on those frames by {extra['gain_back_mean_db']:+.2f} dB on average (all frames: +0.49), positive in "
        f"{extra['share_of_those_clips_with_positive_gain'] * 100:.0f} % of those clips; UV texture coverage {extra['coverage_photo_mean'] * 100:.0f} % from the "
        f"photo -> {extra['coverage_after_mean'] * 100:.0f} % after the update.")
(OUT / "ablation_update.md").write_text("# Ablation of the appearance update (all 163 clips; existing scores)\n\n" + "\n".join(rows_md) + "\n\n" + note + "\n")
(OUT / "ablation_update.tex").write_text("\n".join(T) + "\n"); (OUT / "ablation_update_extra.json").write_text(json.dumps(extra, indent=1) + "\n")
if a.tex: Path(a.tex).parent.mkdir(parents=True, exist_ok=True); Path(a.tex).write_text("\n".join(T) + "\n")
print("\n".join(rows_md)); print(note)
