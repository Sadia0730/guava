def cells(rows):
    """per row: list of formatted cells with best (bold) / second best (underline) inside this group."""
    out = {m: [] for m, *_ in rows}
    for c, _ in COLS:
        for k, d, sgn, _ in MET:
            r = {m: round(V[(m, c, k)], d) for m, *_ in rows}; uniq = sorted(set(r.values()), key=lambda x: -sgn * x)
            for m in r:
                s = f"{r[m]:.{d}f}"
                out[m].append(r"\textbf{" + s + "}" if r[m] == uniq[0] else (r"\underline{" + s + "}" if len(uniq) > 1 and r[m] == uniq[1] else s))
    return out


